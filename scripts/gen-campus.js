function main() {
  const out = RAW.map((row) => {
    const [name, id, cate, lat, lng, aliases] = row;
    const g = coord.wgs84ToGcj02(lng, lat);
    const dist = distanceMeters(lat, lng, g.lat, g.lng);
    return { id, name, cate, lat: g.lat, lng: g.lng, aliases, _offset: dist, _wgs: [lat, lng] };
  });

  console.log('共 ' + out.length + ' 个地点');
  console.log('GCJ-02 相对 WGS-84 的偏移量（米）：最小 ' +
    Math.round(Math.min.apply(null, out.map((o) => o._offset))) + '，最大 ' +
    Math.round(Math.max.apply(null, out.map((o) => o._offset))));
  console.log('');
  console.log('// id | 名称 | 分类 | GCJ-02 坐标');
  out.forEach((o) => {
    console.log([o.id, o.name, o.cate, o.lat, o.lng].join(' | '));
  });
}

function distanceMeters(lat1, lng1, lat2, lng2) {
  const R = 6371008.8;
  const rad = Math.PI / 180;
  const dLat = (lat2 - lat1) * rad;
  const dLng = (lng2 - lng1) * rad;
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(lat1 * rad) * Math.cos(lat2 * rad) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.min(1, Math.sqrt(h)));
}

main();
